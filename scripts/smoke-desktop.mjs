import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

const server = createServer((request, response) => {
  if (request.url === '/download') {
    response.setHeader('content-type', 'text/plain');
    response.setHeader('content-disposition', 'attachment; filename="cove-smoke.txt"');
    response.end('A file that belongs to you.');
    return;
  }
  response.setHeader('content-type', 'text/html');
  response.end(request.url === '/next' ? '<title>Next page</title><h1>Navigation works</h1>' : '<title>Native smoke test</title><h1>Real Chromium browsing</h1><a href="/next">Next</a>');
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const address = `http://127.0.0.1:${server.address().port}`;
const userData = await mkdtemp(path.join(tmpdir(), 'cove-smoke-'));
const env = { ...process.env, COVE_USER_DATA: userData, COVE_DEV_URL: '' };
delete env.ELECTRON_RUN_AS_NODE;
let application;
try {
  application = await electron.launch({ ...(process.env.COVE_TEST_EXECUTABLE ? { executablePath: process.env.COVE_TEST_EXECUTABLE, args: [] } : { args: ['.'] }), env, timeout: 30000 });
  const page = await application.firstWindow();
  await page.waitForSelector('.home-search');
  await page.waitForFunction(() => document.querySelector('.inspiration-card img')?.naturalWidth > 0);
  const initialGuests = await application.evaluate(({ webContents }) => webContents.getAllWebContents().filter(contents => contents.getType() !== 'window').length);
  assert.equal(initialGuests, 0, 'start page must not load hidden external tabs');
  await page.locator('.home-search').click();
  await page.getByRole('combobox', { name: 'Search or enter URL' }).fill(address);
  const guestPromise = application.context().waitForEvent('page', { timeout: 20000 });
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.title === 'Native smoke test — Cove');
  const guest = await guestPromise;
  await guest.getByRole('heading', { name: 'Real Chromium browsing' }).waitFor();
  const safety = await guest.evaluate(() => ({ node: typeof window.require, bridge: typeof window.cove }));
  assert.deepEqual(safety, { node: 'undefined', bridge: 'undefined' });
  const denied = await guest.evaluate(() => new Promise(resolve => navigator.geolocation.getCurrentPosition(() => resolve(false), error => resolve(error.code === 1))));
  assert.equal(denied, true, 'site permissions must be denied by default');
  await guest.getByRole('link', { name: 'Next' }).click();
  await page.waitForFunction(() => document.title === 'Next page — Cove');
  assert.equal(await page.getByRole('button', { name: 'Back', exact: true }).isEnabled(), true);
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.waitForFunction(() => document.title === 'Native smoke test — Cove');
  await guest.getByRole('heading', { name: 'Real Chromium browsing' }).click();
  await application.evaluate(({ webContents }, url) => {
    const contents = webContents.getAllWebContents().find(entry => entry.getURL() === url);
    const modifiers = [process.platform === 'darwin' ? 'meta' : 'control'];
    contents.sendInputEvent({ type: 'keyDown', keyCode: 'L', modifiers });
    contents.sendInputEvent({ type: 'keyUp', keyCode: 'L', modifiers });
  }, `${address}/`);
  await page.getByRole('dialog', { name: 'Navigate to address' }).waitFor();
  await page.getByRole('combobox', { name: 'Search or enter URL' }).fill(`${address}/next`);
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.title === 'Next page — Cove');
  assert.equal(await page.locator('.tab-row').count(), 4, 'address shortcut must navigate the current tab, not add another');
  await application.evaluate(({ webContents }, url) => {
    const contents = webContents.getAllWebContents().find(entry => entry.getURL() === url);
    const modifiers = [process.platform === 'darwin' ? 'meta' : 'control'];
    contents.sendInputEvent({ type: 'keyDown', keyCode: 'F', modifiers });
    contents.sendInputEvent({ type: 'keyUp', keyCode: 'F', modifiers });
  }, `${address}/next`);
  await page.getByRole('search', { name: 'Find in page' }).waitFor();
  await page.getByRole('textbox', { name: 'Find in page', exact: true }).fill('Navigation');
  await page.waitForFunction(() => document.querySelector('.find-count')?.textContent === '1 / 1');
  const findChildCount = await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].contentView.children.length);
  assert.equal(findChildCount, 1, 'find toolbar must not hide the searched page');
  await page.getByRole('button', { name: 'Close find' }).click();
  const activeId = await page.evaluate(() => JSON.parse(localStorage.getItem('cove.workspace.v1')).activeTabId);
  const pdfPath = path.join(userData, 'cove-page.pdf');
  await application.evaluate(({ dialog }, filename) => {
    globalThis.coveOriginalSaveDialog = dialog.showSaveDialog;
    dialog.showSaveDialog = async () => ({ canceled: false, filePath: filename });
  }, pdfPath);
  try {
    const pdfResult = await page.evaluate(id => window.cove.savePdf(id), activeId);
    assert.equal(pdfResult.success, true, 'PDF bridge completes after writing the file');
    assert.equal((await readFile(pdfPath)).subarray(0, 5).toString(), '%PDF-', 'real Chromium produces a PDF');
    await application.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true }); });
    assert.equal((await page.evaluate(id => window.cove.savePdf(id), activeId)).cancelled, true);
  } finally {
    await application.evaluate(({ dialog }) => { dialog.showSaveDialog = globalThis.coveOriginalSaveDialog; delete globalThis.coveOriginalSaveDialog; });
  }
  await page.evaluate(id => window.cove.openDevTools(id), activeId);
  await expect.poll(() => application.evaluate(({ webContents }, url) => webContents.getAllWebContents().find(contents => contents.getURL() === url)?.isDevToolsOpened(), `${address}/next`)).toBe(true);
  await application.evaluate(({ webContents }, url) => webContents.getAllWebContents().find(contents => contents.getURL() === url).closeDevTools(), `${address}/next`);
  await page.evaluate(id => window.cove.hardReload(id), activeId);
  await guest.getByRole('heading', { name: 'Navigation works' }).waitFor();
  const zoom = await page.evaluate(id => window.cove.setZoom({ tabId: id, factor: 1.3 }), activeId);
  assert.ok(Math.abs(zoom - 1.3) < 0.01, 'native page zoom works');
  assert.equal(await page.evaluate(id => window.cove.setMuted({ tabId: id, muted: true }), activeId), true);
  await page.evaluate(id => window.cove.setZoom({ tabId: id, factor: 1 }), activeId);
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'History', exact: true }).click();
  await page.getByRole('dialog', { name: 'history' }).getByText('Next page', { exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  const savePath = path.join(userData, 'cove-smoke.txt');
  await application.evaluate(({ session }, filename) => {
    session.fromPartition('persist:cove-personal').once('will-download', (_event, item) => item.setSavePath(filename));
  }, savePath);
  await guest.evaluate(url => { const anchor = document.createElement('a'); anchor.href = url; anchor.download = ''; document.body.append(anchor); anchor.click(); }, `${address}/download`);
  await page.waitForFunction(async () => (await window.cove.getDownloads()).some(item => item.filename === 'cove-smoke.txt' && item.state === 'completed'));
  await expect.poll(() => readFile(savePath, 'utf8').catch(() => null)).toBe('A file that belongs to you.');
  await page.getByRole('button', { name: 'Downloads', exact: true }).click();
  await page.getByRole('dialog', { name: 'downloads' }).getByText('cove-smoke.txt', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Show cove-smoke.txt in folder' }).waitFor();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: /Split view/ }).click();
  const panes = await page.locator('.browser-pane').count();
  assert.equal(panes, 2);
  await page.locator('.browser-pane').nth(1).locator('.pane-caption').click();
  await page.locator('.address-bar').click();
  await page.getByRole('combobox', { name: 'Search or enter URL' }).fill(`${address}/right`);
  const rightGuestPromise = application.context().waitForEvent('page', { timeout: 20000 });
  await page.keyboard.press('Enter');
  const rightGuest = await rightGuestPromise;
  await rightGuest.getByRole('heading', { name: 'Real Chromium browsing' }).waitFor();
  const sendRightShortcut = (key, shift = false) => application.evaluate(({ webContents }, { url, key, shift }) => {
    const contents = webContents.getAllWebContents().find(entry => entry.getURL() === url);
    contents.focus();
    const modifiers = [process.platform === 'darwin' ? 'meta' : 'control', ...(shift ? ['shift'] : [])];
    contents.sendInputEvent({ type: 'keyDown', keyCode: key, modifiers });
    contents.sendInputEvent({ type: 'keyUp', keyCode: key, modifiers });
  }, { url: `${address}/right`, key, shift });
  await sendRightShortcut('L');
  await page.getByRole('dialog', { name: 'Navigate to address' }).waitFor();
  assert.equal(await page.getByRole('combobox', { name: 'Search or enter URL' }).inputValue(), `${address}/right`);
  await page.keyboard.press('Escape');
  await guest.getByRole('heading', { name: 'Navigation works' }).click();
  await sendRightShortcut('F');
  await page.getByRole('textbox', { name: 'Find in page', exact: true }).fill('Chromium');
  await page.waitForFunction(() => document.querySelector('.find-count')?.textContent === '1 / 1');
  await page.getByRole('button', { name: 'Close find' }).click();
  await sendRightShortcut('=');
  await page.waitForFunction(() => document.querySelector('.zoom-indicator')?.textContent === '110%');
  const splitZoom = await application.evaluate(({ webContents }, base) => Object.fromEntries(webContents.getAllWebContents().filter(entry => [base + '/next', base + '/right'].includes(entry.getURL())).map(entry => [new URL(entry.getURL()).pathname, entry.getZoomFactor()])), address);
  assert.ok(Math.abs(splitZoom['/right'] - 1.1) < .01);
  assert.ok(Math.abs(splitZoom['/next'] - 1) < .01);
  await sendRightShortcut('J');
  await page.getByRole('dialog', { name: 'downloads' }).waitFor();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  const rightReload = rightGuest.waitForEvent('domcontentloaded');
  await sendRightShortcut('R');
  await rightReload;
  assert.equal(await page.locator('.browser-pane').count(), 2, 'focusing the secondary pane must not swap or close panes');
  await sendRightShortcut('S', true);
  await page.waitForFunction(() => document.querySelector('.app').classList.contains('sidebar-hidden'));
  await sendRightShortcut('S', true);
  await page.waitForFunction(() => !document.querySelector('.app').classList.contains('sidebar-hidden'));
  const originalPaneIds = await page.locator('.browser-pane').evaluateAll(panes => panes.map(pane => pane.dataset.tabId));
  await page.getByRole('separator', { name: 'Resize split view' }).focus();
  await page.keyboard.press('ArrowRight');
  await page.getByRole('button', { name: 'Swap split panes' }).first().click();
  assert.deepEqual(await page.locator('.browser-pane').evaluateAll(panes => panes.map(pane => pane.dataset.tabId)), [...originalPaneIds].reverse());
  await page.reload();
  await page.waitForFunction(() => document.querySelectorAll('.browser-pane').length === 2);
  assert.deepEqual(await page.locator('.browser-pane').evaluateAll(panes => panes.map(pane => pane.dataset.tabId)), [...originalPaneIds].reverse(), 'native pane order persists after shell reload');
  assert.equal(await page.getByRole('separator').getAttribute('aria-valuenow'), '45', 'swapped ratio persists');
  await sendRightShortcut('W');
  await page.waitForFunction(() => document.querySelectorAll('.browser-pane').length === 1);
  assert.equal(await guest.url(), `${address}/next`, 'closing the secondary pane preserves the primary page');
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  const childCount = await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].contentView.children.length);
  assert.equal(childCount, 0, 'native guest must be hidden behind the settings dialog');
  console.log('Desktop smoke: sandbox, permissions, history, downloads, saved/swapped splits, split-pane focus/address/find/zoom/reload/close, overlay hiding PASS');
} finally {
  await application?.close();
  await new Promise(resolve => server.close(resolve));
}
